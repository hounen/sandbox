      subroutine getbsbk(yy, bbs,bbk)                                           !/*ge          1*/
#ifdef CEM                                                                      /*!ge          2*/
! ======================================================================        !/*ge          3*/
!                                                                               !/*ge          4*/
!     Provides the saddle point shape parameters BS and BK from                 !/*ge          5*/
!     tables given by:                                                          !/*ge          6*/
!     Myers & Swiatecki, Annals of Physics 84, p. 186-210, (1974)               !/*ge          7*/
!                                                                               !/*ge          8*/
!     called by: WAMM                                                           !/*ge          9*/
!                                                                               !/*ge         10*/
!     CEM95 written by S. G. Mashnik                                            !/*ge         11*/
!                                                                               !/*ge         12*/
!     Written by F. Gallmeier, ORNL CPED, July 1998                             !/*ge         13*/
!     Changed to double by F. Gallmeier, ORNL CPED, October 1998                !/*ge         14*/
!                                                                               !/*ge         15*/
! ======================================================================        !/*ge         16*/
#include <cem/cdouble.h>                                                        /*!ge         17*/
      dimension y(51), bs(51), bk(51)                                           !/*ge         18*/
!   Values of the deformation parameter y for LDM                               !/*ge         19*/
      data y/                                                                   !/*ge         20*/
     &      0.00d0,     0.02d0,     0.04d0,     0.06d0,     0.08d0,             !/*ge         21*/
     &      0.10d0,     0.12d0,     0.14d0,     0.16d0,     0.18d0,             !/*ge         22*/
     &      0.20d0,     0.22d0,     0.24d0,     0.26d0,     0.28d0,             !/*ge         23*/
     &      0.30d0,     0.32d0,     0.34d0,     0.36d0,     0.38d0,             !/*ge         24*/
     &      0.40d0,     0.42d0,     0.44d0,     0.46d0,     0.48d0,             !/*ge         25*/
     &      0.50d0,     0.52d0,     0.54d0,     0.56d0,     0.58d0,             !/*ge         26*/
     &      0.60d0,     0.62d0,     0.64d0,     0.66d0,     0.68d0,             !/*ge         27*/
     &      0.70d0,     0.72d0,     0.74d0,     0.76d0,     0.78d0,             !/*ge         28*/
     &      0.80d0,     0.82d0,     0.84d0,     0.86d0,     0.88d0,             !/*ge         29*/
     &      0.90d0,     0.92d0,     0.94d0,     0.96d0,     0.98d0,             !/*ge         30*/
     &      1.00d0/                                                             !/*ge         31*/
      data bs/                                                                  !/*ge         32*/
     &   1.00000d0,  1.00086d0,  1.00338d0,  1.00750d0,  1.01319d0,             !/*ge         33*/
     &   1.02044d0,  1.02927d0,  1.03974d0,  1.05195d0,  1.06604d0,             !/*ge         34*/
     &   1.08224d0,  1.10085d0,  1.12229d0,  1.14717d0,  1.17623d0,             !/*ge         35*/
     &   1.20963d0,  1.24296d0,  1.26532d0,  1.27610d0,  1.28126d0,             !/*ge         36*/
     &   1.28362d0,  1.28235d0,  1.28477d0,  1.28450d0,  1.28394d0,             !/*ge         37*/
     &   1.28320d0,  1.28235d0,  1.28141d0,  1.28042d0,  1.27941d0,             !/*ge         38*/
     &   1.27837d0,  1.27732d0,  1.27627d0,  1.27522d0,  1.27418d0,             !/*ge         39*/
     &   1.27314d0,  1.27210d0,  1.27108d0,  1.27006d0,  1.26906d0,             !/*ge         40*/
     &   1.26806d0,  1.26707d0,  1.26610d0,  1.26514d0,  1.26418d0,             !/*ge         41*/
     &   1.26325d0,  1.26233d0,  1.26147d0,  1.26100d0,  1.26050d0,             !/*ge         42*/
     &   1.25992d0/                                                             !/*ge         43*/
      data bk/                                                                  !/*ge         44*/
     &   1.00000d0,  1.00087d0,  1.00352d0,  1.00799d0,  1.01433d0,             !/*ge         45*/
     &   1.02265d0,  1.03306d0,  1.04576d0,  1.06099d0,  1.07910d0,             !/*ge         46*/
     &   1.10056d0,  1.12603d0,  1.15651d0,  1.19348d0,  1.23915d0,             !/*ge         47*/
     &   1.29590d0,  1.35951d0,  1.41013d0,  1.44103d0,  1.46026d0,             !/*ge         48*/
     &   1.47339d0,  1.48308d0,  1.49068d0,  1.49692d0,  1.50226d0,             !/*ge         49*/
     &   1.50694d0,  1.51114d0,  1.51502d0,  1.51864d0,  1.52208d0,             !/*ge         50*/
     &   1.52539d0,  1.52861d0,  1.53177d0,  1.53490d0,  1.53803d0,             !/*ge         51*/
     &   1.54117d0,  1.54473d0,  1.54762d0,  1.55096d0,  1.55440d0,             !/*ge         52*/
     &   1.55798d0,  1.56173d0,  1.56567d0,  1.56980d0,  1.57413d0,             !/*ge         53*/
     &   1.57860d0,  1.58301d0,  1.58688d0,  1.58705d0,  1.58723d0,             !/*ge         54*/
     &   1.58740d0/                                                             !/*ge         55*/
      i = yy*50+1                                                               !/*ge         56*/
      dy = yy - y(i)                                                            !/*ge         57*/
      bbs = bs(i) + (bs(i+1)-bs(i))/dp2m2*dy                                    !/*ge         58*/
      bbk = bk(i) + (bk(i+1)-bk(i))/dp2m2*dy                                    !/*ge         59*/
#endif                                                                          /*!ge         60*/
      return                                                                    !/*ge         61*/
      end                                                                       !/*ge         62*/
