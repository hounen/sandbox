!                                                                               !/*gl         62*/
      x = ran_num()                                                             !/*gl         63*/
      if(x .lt. 0.004) then                                                     !/*gl         64*/
!                                                                               !/*gl         65*/
!         extreme left-hand tail                                                !/*gl         66*/
          yran = -sqrt(abs(log(x)))                                             !/*gl         67*/
!                                                                               !/*gl         68*/
      elseif(x.le.range1) then                                                  !/*gl         69*/
!                                                                               !/*gl         70*/
!         4-point interpolation in the first cumulative table                   !/*gl         71*/
          tabpo1 = (x-x1bot)*gp1inv                                             !/*gl         72*/
          j = tabpo1 + 1                                                        !/*gl         73*/
          j = max(j,2)                                                          !/*gl         74*/
          j = min(j,98)                                                         !/*gl         75*/
          p = tabpo1 - (j-1)                                                    !/*gl         76*/
          a = (p+1.0) * xcum1(j+2) - (p-2.0) * xcum1(j-1)                       !/*gl         77*/
          b = (p-1.0) * xcum1(j)   - p       * xcum1(j+1)                       !/*gl         78*/
          yran = a*p*(p-1.0)*0.16666667+b*(p+1.0)*(p-2.0)*0.5                   !/*gl         79*/
!                                                                               !/*gl         80*/
      elseif(x.le.range2) then                                                  !/*gl         81*/
!                                                                               !/*gl         82*/
!         4-point interpolation in the first cumulative table                   !/*gl         83*/
          tabpo2 = (x-x2bot)*gp2inv                                             !/*gl         84*/
          j = tabpo2 + 1                                                        !/*gl         85*/
          j = max(j,2)                                                          !/*gl         86*/
          j = min(j,98)                                                         !/*gl         87*/
          p = tabpo2 - (j-1)                                                    !/*gl         88*/
          a = (p+1.0) * xcum2(j+2) - (p-2.0) * xcum2(j-1)                       !/*gl         89*/
          b = (p-1.0) * xcum2(j)   - p       * xcum2(j+1)                       !/*gl         90*/
          yran = a*p*(p-1.0)*0.16666667+b*(p+1.0)*(p-2.0)*0.5                   !/*gl         91*/
!                                                                               !/*gl         92*/
      else                                                                      !/*gl         93*/
!                                                                               !/*gl         94*/
!         1/x**2 sampling for extreme landau tail                               !/*gl         95*/
          yran=200./ran_num()                                                   !/*gl         96*/
!                                                                               !/*gl         97*/
      endif                                                                     !/*gl         98*/
      return                                                                    !/*gl         99*/
      end                                                                       !/*gl        100*/
