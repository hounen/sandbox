      subroutine glandg(ran_num,yran)                                           !/*gl          2*/
!                                                                               !/*gl          3*/
!     ********************************************************                  !/*gl          4*/
!     *                                                      *                  !/*gl          5*/
!     *  copy of the cern library routine genlan             *                  !/*gl          6*/
!     *  generation of landau-distributed random numbers by  *                  !/*gl          7*/
!     *  4-point interpolation in the previously-tabulated   *                  !/*gl          8*/
!     *  inverse cumulative distribution.                    *                  !/*gl          9*/
!     *                                                      *                  !/*gl         10*/
!     *    ==>called by : glando                             *                  !/*gl         11*/
!     *                                                      *                  !/*gl         12*/
!     ********************************************************                  !/*gl         13*/
!                                                                               !/*gl         14*/
#include <gvaviv/double.h>                                                      /*!gl         15*/
      external ran_num                                                          !/*gl         16*/
      parameter (range1=0.807069d0, range2=0.994869d0)                          !/*gl         17*/
      parameter (x1bot =0.0d0, x2bot =0.79124d0)                                !/*gl         18*/
      parameter (gp1inv=118.836d0, gp2inv=486.178d0)                            !/*gl         19*/
!                                                                               !/*gl         20*/
      dimension xcum1(100), xcum2(100)                                          !/*gl         21*/
!                                                                               !/*gl         22*/
!     table 1 of inverse cumulative landau points (0 < p < .833)                !/*gl         23*/
      data (xcum1(i),i=1,100) /                                                 !/*gl         24*/
     & -2.5700d0,-2.15412d0,-1.94167d0,-1.79583d0,-1.67975d0,-1.58090d0,        !/*gl         25*/
     &-1.49341d0,-1.41397d0,-1.34057d0,-1.27185d0,-1.20686d0,-1.14490d0,        !/*gl         26*/
     &-1.08545d0,-1.02809d0,-0.97249d0,-0.91839d0,-0.86557d0,-0.81386d0,        !/*gl         27*/
     &-0.76308d0,-0.71311d0,-0.66384d0,-0.61515d0,-0.56696d0,-0.51919d0,        !/*gl         28*/
     &-0.47176d0,-0.42462d0,-0.37769d0,-0.33092d0,-0.28426d0,-0.23767d0,        !/*gl         29*/
     &-0.19109d0,-0.14447d0,-0.09779d0,-0.05100d0,-0.00405d0, 0.04308d0,        !/*gl         30*/
     & 0.09044d0, 0.13806d0, 0.18598d0, 0.23423d0, 0.28285d0, 0.33187d0,        !/*gl         31*/
     & 0.38134d0, 0.43128d0, 0.48174d0, 0.53275d0, 0.58435d0, 0.63658d0,        !/*gl         32*/
     & 0.68948d0, 0.74309d0, 0.79746d0, 0.85263d0, 0.90865d0, 0.96556d0,        !/*gl         33*/
     & 1.02342d0, 1.08228d0, 1.14219d0, 1.20322d0, 1.26542d0, 1.32887d0,        !/*gl         34*/
     & 1.39362d0, 1.45976d0, 1.52736d0, 1.59650d0, 1.66727d0, 1.73976d0,        !/*gl         35*/
     & 1.81407d0, 1.89032d0, 1.96860d0, 2.04905d0, 2.13180d0, 2.21699d0,        !/*gl         36*/
     & 2.30477d0, 2.39531d0, 2.48878d0, 2.58540d0, 2.68535d0, 2.78889d0,        !/*gl         37*/
     & 2.89626d0, 3.00775d0, 3.12364d0, 3.24429d0, 3.37005d0, 3.50136d0,        !/*gl         38*/
     & 3.63866d0, 3.78246d0, 3.93334d0, 4.09194d0, 4.25900d0, 4.43533d0,        !/*gl         39*/
     & 4.62186d0, 4.81960d0, 5.02974d0, 5.25368d0, 5.49312d0, 5.74987d0,        !/*gl         40*/
     & 6.02605d0, 6.32428d0, 6.64773d0, 7.00000d0/                              !/*gl         41*/
!                                                                               !/*gl         42*/
!     table 2 of inverse cumulative landau points (.791 < p < .995)             !/*gl         43*/
      data (xcum2(i),i=1,100) /                                                 !/*gl         44*/
     & 5.50000d0, 5.56120d0, 5.62347d0, 5.68684d0, 5.75133d0, 5.81699d0,        !/*gl         45*/
     & 5.88383d0, 5.95191d0, 6.02125d0, 6.09190d0, 6.16391d0, 6.23732d0,        !/*gl         46*/
     & 6.31219d0, 6.38855d0, 6.46646d0, 6.54597d0, 6.62712d0, 6.70998d0,        !/*gl         47*/
     & 6.79460d0, 6.88103d0, 6.96935d0, 7.05962d0, 7.15192d0, 7.24633d0,        !/*gl         48*/
     & 7.34294d0, 7.44182d0, 7.54306d0, 7.64676d0, 7.75300d0, 7.86188d0,        !/*gl         49*/
     & 7.97351d0, 8.08800d0, 8.20548d0, 8.32610d0, 8.44997d0, 8.57725d0,        !/*gl         50*/
     & 8.70808d0, 8.84262d0, 8.98103d0, 9.12349d0, 9.27021d0, 9.42141d0,        !/*gl         51*/
     & 9.57730d0, 9.73812d0, 9.90410d0,10.07552d0,10.25265d0,10.43584d0,        !/*gl         52*/
     &10.62540d0,10.82169d0,11.02508d0,11.23598d0,11.45487d0,11.68222d0,        !/*gl         53*/
     &11.91855d0,12.16441d0,12.42045d0,12.68734d0,12.96580d0,13.25663d0,        !/*gl         54*/
     &13.56075d0,13.87912d0,14.21280d0,14.56296d0,14.93088d0,15.31799d0,        !/*gl         55*/
     &15.72593d0,16.15650d0,16.61170d0,17.09378d0,17.60523d0,18.14884d0,        !/*gl         56*/
     &18.72792d0,19.34622d0,20.00796d0,20.71792d0,21.48176d0,22.30618d0,        !/*gl         57*/
     &23.19862d0,24.16809d0,25.22547d0,26.38320d0,27.65658d0,29.06490d0,        !/*gl         58*/
     &30.63048d0,32.38211d0,34.35555d0,36.59607d0,39.16212d0,42.13195d0,        !/*gl         59*/
     &45.61204d0,49.74758d0,54.74189d0,60.89935d0,68.67370d0,78.81480d0,        !/*gl         60*/
