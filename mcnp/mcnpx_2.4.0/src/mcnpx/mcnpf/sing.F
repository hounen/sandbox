!#ident sing.F from deck sn                                                     !/*sn          1*/
      subroutine sing(il,e,ra,p,lx)                                             !/*sn          2*/
!        calculate components p of the single-scattering cross section.         !/*sn          3*/
!        il=1 for beginning of centered electron substep.                       !/*sn          4*/
!        il=2 for end of substep.  calculate only the first component.          !/*sn          5*/
!        e = energy of the electron.                                            !/*sn          6*/
!        ra = range of the electron.                                            !/*sn          7*/
!        lx = number of components calculated for il=1.                         !/*sn          8*/
      use global_data                                                           !/*snx         1*/
!                                                                               !/*snx         2*/
      implicit real(kindr) (a-h,o-z)                                            !/*snx         3*/
      implicit integer(kindi) (i-n)                                             !/*snx         4*/
!                                                                               !/*snx         5*/
      dimension p(240),ta(3,280),am(5,6),ap(5,6),ca(280)                        !/*sn         10*/
      data (ca(i),i=  1, 86)/      .08999,.09031,.09064,.09097,.09131,          !/*sn         11*/
     & .09164,.09198,.09232,.09267,.09301,.09336,.09371,.09407,.09442,          !/*sn         12*/
     & .09479,.09515,.09551,.09588,.09625,.09663,.09700,.09738,.09777,          !/*sn         13*/
     & .09815,.09854,.09893,.09933,.09973,.10013,.10054,.10094,.10136,          !/*sn         14*/
     & .10177,.10219,.10261,.10304,.10347,.10390,.10434,.10478,.10522,          !/*sn         15*/
     & .10567,.10612,.10657,.10703,.10750,.10796,.10844,.10891,.10939,          !/*sn         16*/
     & .10988,.11037,.11086,.11136,.11186,.11237,.11288,.11339,.11391,          !/*sn         17*/
     & .11444,.11497,.11551,.11605,.11659,.11714,.11770,.11826,.11883,          !/*sn         18*/
     & .11940,.11998,.12057,.12116,.12175,.12235,.12296,.12357,.12419,          !/*sn         19*/
     & .12482,.12545,.12609,.12674,.12739,.12805,.12872,.12939,.13008/          !/*sn         20*/
      data (ca(i),i= 87,172)/      .13076,.13146,.13216,.13287,.13359,          !/*sn         21*/
     & .13432,.13506,.13580,.13655,.13731,.13808,.13886,.13964,.14044,          !/*sn         22*/
     & .14125,.14206,.14288,.14372,.14456,.14542,.14628,.14716,.14804,          !/*sn         23*/
     & .14894,.14985,.15077,.15170,.15264,.15360,.15456,.15554,.15654,          !/*sn         24*/
     & .15754,.15856,.15959,.16064,.16170,.16278,.16387,.16497,.16609,          !/*sn         25*/
     & .16723,.16838,.16955,.17074,.17194,.17316,.17440,.17566,.17693,          !/*sn         26*/
     & .17823,.17954,.18087,.18223,.18361,.18500,.18642,.18786,.18933,          !/*sn         27*/
     & .19082,.19233,.19387,.19543,.19702,.19864,.20028,.20196,.20366,          !/*sn         28*/
     & .20539,.20715,.20894,.21076,.21262,.21451,.21643,.21839,.22039,          !/*sn         29*/
     & .22242,.22450,.22661,.22876,.23096,.23319,.23547,.23780,.24017/          !/*sn         30*/
      data (ca(i),i=173,258)/      .24260,.24507,.24759,.25016,.25279,          !/*sn         31*/
     & .25547,.25821,.26100,.26386,.26678,.26976,.27281,.27593,.27911,          !/*sn         32*/
     & .28237,.28570,.28910,.29259,.29615,.29980,.30353,.30735,.31126,          !/*sn         33*/
     & .31526,.31936,.32355,.32785,.33225,.33676,.34138,.34611,.35096,          !/*sn         34*/
     & .35593,.36102,.36623,.37158,.37706,.38267,.38842,.39433,.40038,          !/*sn         35*/
     & .40658,.41293,.41944,.42611,.43295,.43995,.44713,.45449,.46202,          !/*sn         36*/
     & .46973,.47763,.48572,.49399,.50246,.51112,.51998,.52903,.53828,          !/*sn         37*/
     & .54773,.55737,.56722,.57726,.58749,.59791,.60853,.61932,.63030,          !/*sn         38*/
     & .64144,.65275,.66421,.67583,.68757,.69944,.71142,.72349,.73564,          !/*sn         39*/
     & .74785,.76010,.77236,.78462,.79685,.80902,.82111,.83308,.84491/          !/*sn         40*/
      data (ca(i),i=259,280)/      .85656,.86801,.87921,.89013,.90073,          !/*sn         41*/
     & .91098,.92085,.93029,.93927,.94775,.95570,.96308,.96987,.97603,          !/*sn         42*/
     & .98154,.98636,.99049,.99389,.99655,.99847,.99962,1./                     !/*sn         43*/
!                                                                               !/*sn         44*/
      s=e/gpt(3)                                                                !/*sn         45*/
      t4=s*(s+2.)                                                               !/*sn         46*/
      bs=t4/(s+1.)**2                                                           !/*sn         47*/
      do 210 ic=jmd(ljmd+mkc),jmd(ljmd+mkc+1)-1                                 !/*sn         48*/
      ix=lme(llme+3,ic)                                                         !/*sn         49*/
      z=iza(liza+ic)/1000                                                       !/*sn         50*/
      u=z/(fscon*sqrt(bs))                                                      !/*sn         51*/
!        the constant 3.1329 is 4. * 0.885**2                                   !/*sn4b        4*/
      ea=(1.13+3.76*sqrt(s/(s+1.))*u**2)*z**(2.*third)/(3.1329*t4*              !/*sn4b        5*/
     & fscon**2)                                                                !/*sn4b        6*/
      if(e.gt..256)go to 20                                                     !/*sn         53*/
!                                                                               !/*sn         54*/
!        energy < .256 mev                                                      !/*sn         55*/
      kx=2                                                                      !/*sn         56*/
      if(il.eq.1)kx=min(max(51,int(exp(1.794-.397*log(ea)))),240)               !/*sn         57*/
      ae=log(e*1000.)                                                           !/*sn         58*/
      j=min(max(1,int(log(.256/e)/log(two))),7)                                 !/*snx         6*/
      x1=log(exs(jxs(ljxs+4,ix)+14*(j-1)))                                      !/*sn         60*/
      x2=log(exs(jxs(ljxs+4,ix)+14*j))                                          !/*sn         61*/
      x3=log(exs(jxs(ljxs+4,ix)+14*(j+1)))                                      !/*sn         62*/
      dd=(x1**2)*(x2-x3)-(x2**2)*(x1-x3)+(x3**2)*(x1-x2)                        !/*sn         63*/
      cl=28076630.*(z+1.)*ra*fme(lfme+ic)/z                                     !/*sn         64*/
      do 10 l=2,kx                                                              !/*sn         65*/
      c1=exs(jxs(ljxs+7,ix)+l-2+240*(j-1))                                      !/*sn         66*/
      c2=exs(jxs(ljxs+7,ix)+l-2+240*j)                                          !/*sn         67*/
      c3=exs(jxs(ljxs+7,ix)+l-2+240*(j+1))                                      !/*sn         68*/
      ad=c1*(x2-x3)-c2*(x1-x3)+c3*(x1-x2)                                       !/*sn         69*/
      bd=(x1**2)*(c2-c3)-(x2**2)*(c1-c3)+(x3**2)*(c1-c2)                        !/*sn         70*/
      cd=(x1**2)*(x2*c3-x3*c2)-(x2**2)*(x1*c3-x3*c1)+                           !/*sn         71*/
     & (x3**2)*(x1*c2-x2*c1)                                                    !/*sn         72*/
   10 p(l+1-il)=p(l+1-il)+cl*exp((ad*ae**2+bd*ae+cd)/dd)                        !/*sn         73*/
      go to 210                                                                 !/*sn         74*/
!                                                                               !/*sn         75*/
!        energy > .256 mev                                                      !/*sn         76*/
   20 e1=1.+1./ea                                                               !/*sn         77*/
      e3=1.+2.*ea                                                               !/*sn         78*/
      e4=1./(1.+ea)                                                             !/*sn         79*/
      e7=log(e1)-e4                                                             !/*sn         80*/
      ae=1.-2.*ea*(sqrt(e1)-1.)                                                 !/*sn         81*/
      af=4.*ae*sqrt(ae)/(ae+1.)                                                 !/*sn         82*/
      wq=.499*z*(z+1)*ra*fme(lfme+ic)/(t4*bs)                                   !/*sn         83*/
      cf=0.                                                                     !/*sn         84*/
      if(u.gt.2.79)go to 30                                                     !/*sn         85*/
      i=min(max(2,280-nint(100.*u)),279)                                        !/*sn         86*/
      t=100.*u+i-280                                                            !/*sn         87*/
      cf=(.5*t*((t+1.)*ca(i-1)+(t-1.)*ca(i+1))+(1.-t**2)*ca(i))*pie*u*bs        !/*sn         88*/
   30 do 50 j=1,5                                                               !/*sn         89*/
      y=1.-cos((j-1)*.25*pie)+2.*ea                                             !/*sn         90*/
      am(j,6)=qpol(e,exs(jxs(ljxs+3,ix)),exs(jxs(ljxs+3,ix)+                    !/*sn         91*/
     & nxs(lnxs+4,ix)*j),nxs(lnxs+4,ix))-1.-cf*sqrt(.5*y)                       !/*sn         92*/
      am(j,1)=1.                                                                !/*sn         93*/
      do 40 jk=2,5                                                              !/*sn         94*/
   40 am(j,jk)=am(j,jk-1)*y                                                     !/*sn         95*/
      do 50 m=1,6                                                               !/*sn         96*/
   50 ap(j,m)=am(j,m)                                                           !/*sn         97*/
      do 90 j=1,4                                                               !/*sn         98*/
      mx=j                                                                      !/*sn         99*/
      do 60 n=j+1,5                                                             !/*sn        100*/
   60 if(abs(ap(n,j)).gt.abs(ap(mx,j)))mx=n                                     !/*sn        101*/
      if(mx.eq.j)go to 80                                                       !/*sn        102*/
      do 70 m=1,6                                                               !/*sn        103*/
      t=ap(mx,m)                                                                !/*sn        104*/
      ap(mx,m)=ap(j,m)                                                          !/*sn        105*/
   70 ap(j,m)=t                                                                 !/*sn        106*/
   80 if(abs(ap(j,j)).lt.1e-6*abs(ap(1,1)))call expire(0,'sing',                !/*sn        107*/
     & 'am is an ill-conditioned matrix.')                                      !/*sn        108*/
      do 90 n=j+1,5                                                             !/*sn        109*/
      t=-ap(n,j)/ap(j,j)                                                        !/*sn        110*/
      do 90 m=j+1,6                                                             !/*sn        111*/
   90 ap(n,m)=ap(n,m)+t*ap(j,m)                                                 !/*sn        112*/
      do 110 n=0,4                                                              !/*sn        113*/
      t=0.                                                                      !/*sn        114*/
      do 100 m=1,n                                                              !/*sn        115*/
  100 t=t+ap(5-n,6-m)*am(6-m,6)                                                 !/*sn        116*/
  110 am(5-n,6)=(ap(5-n,6)-t)/ap(5-n,5-n)                                       !/*sn        117*/
      if(il.eq.1)go to 120                                                      !/*sn        118*/
      p(1)=p(1)+wq*((1.+am(1,6))*e7+cf*af+am(2,6)*(2.*e4+e7-e3*e7)+2.*          !/*sn        119*/
     & (am(3,6)+am(4,6)*(e3+third)+am(5,6)*(e3**2+2.*third*e3+third)))          !/*sn        120*/
      go to 210                                                                 !/*sn        121*/
  120 kx=min(max(10,int(exp(1.794-.397*log(ea)))),240)                          !/*sn        122*/
      la=kx+40                                                                  !/*sn        123*/
      ta(1,1)=0.                                                                !/*sn        124*/
      if(ea.gt..0001)go to 140                                                  !/*sn        125*/
      ta(1,2)=e7                                                                !/*sn        126*/
      do 130 l=3,kx+1                                                           !/*sn        127*/
  130 ta(1,l)=((2*l-3)*e3*ta(1,l-1)-(l-1)*ta(1,l-2)-(2*l-3)*e4)/(l-2)           !/*sn        128*/
      go to 170                                                                 !/*sn        129*/
  140 ta(1,la)=0.                                                               !/*sn        130*/
      ta(1,la-1)=1e-25                                                          !/*sn        131*/
      do 150 ll=1,la-3                                                          !/*sn        132*/
      l=la-1-ll                                                                 !/*sn        133*/
  150 ta(1,l)=((2*l+1)*ta(1,l+1)*e3-l*ta(1,l+2))/(l+1)                          !/*sn        134*/
      tf=(e7-e4/(2.*ea))/ta(1,2)                                                !/*sn        135*/
      do 160 l=3,kx+1                                                           !/*sn        136*/
  160 ta(1,l)=ta(1,l)*tf+e4/(2.*ea)                                             !/*sn        137*/
      ta(1,2)=e7                                                                !/*sn        138*/
  170 ta(2,2)=af                                                                !/*sn        139*/
      sm=1.                                                                     !/*sn        140*/
      ar=1.                                                                     !/*sn        141*/
      do 180 l=3,kx                                                             !/*sn        142*/
      ar=ar*ae                                                                  !/*sn        143*/
      sm=sm+ar                                                                  !/*sn        144*/
  180 ta(2,l)=af*sm                                                             !/*sn        145*/
      do 190 l=2,kx                                                             !/*sn        146*/
  190 ta(3,l)=e3*ta(1,l)+ta(1,2)-(l*ta(1,l+1)+(l-1)*ta(1,l-1))/(2*l-1)          !/*sn        147*/
      p(2)=p(2)+wq*((1.+am(1,6))*ta(1,2)+cf*ta(2,2)+am(2,6)*ta(3,2)+2.*         !/*sn        148*/
     & (am(3,6)+am(4,6)*(e3+third)+am(5,6)*(e3**2+2.*third*e3+third)))          !/*sn        149*/
      p(3)=p(3)+wq*((1.+am(1,6))*ta(1,3)+cf*ta(2,3)+am(2,6)*ta(3,3)+            !/*sn        150*/
     & 2.*(am(3,6)+am(4,6)*e3+am(5,6)*(e3**2+.6*third)))                        !/*sn        151*/
      do 200 l=4,kx                                                             !/*sn        152*/
  200 p(l)=p(l)+wq*((1.+am(1,6))*ta(1,l)+cf*ta(2,l)+am(2,6)*ta(3,l)+            !/*sn        153*/
     & 2.*(am(3,6)+am(4,6)*e3+am(5,6)*(e3**2+third)))                           !/*sn        154*/
  210 if(il.eq.1)lx=max(lx,kx)                                                  !/*sn        155*/
      return                                                                    !/*sn        156*/
      end                                                                       !/*sn        157*/
