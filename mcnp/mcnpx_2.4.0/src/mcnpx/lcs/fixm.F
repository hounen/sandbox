      subroutine fixm (z,a,xm)                                                  !/*fi          2*/
#include <lcs/double.h>                                                         /*!fi          3*/
#include <lcs/ercom.h>                                                          /*!fi          4*/
      dimension jprime(250)                                                     !/*fi          5*/
      data jprime /19*0,10*1,8*2,7*3,7*4,6*5,5*6,6*7,5*8,5*9,5*10,5*11,4        !/*fi          6*/
     & *12,5*13,4*14,4*15,4*16,4*17,4*18,4*19,4*20,4*21,4*22,3*23,4*24,4        !/*fi          7*/
     & *25,3*26,4*27,3*28,4*29,3*30,3*31,4*32,3*33,3*34,4*35,3*36,3*37,3        !/*fi          8*/
     & *38,3*39,3*40,3*41,3*42,3*43,3*44,3*45,3*46,3*47,3*48,3*49,3*50,3        !/*fi          9*/
     & *51,3*52,3*53,3*54,55,55,3*56,3*57,3*58,2*59,2*60/                       !/*fi         10*/
      data delamu /0.296064d0/                                                  !/*fi         11*/
      ia=a                                                                      !/*fi         12*/
      iz=z                                                                      !/*fi         13*/
      j=ia-2*iz-jprime(ia)+10                                                   !/*fi         14*/
      if (j.ge.1.and.j.le.20) waps(ia,j)=xm+delamu*ia                           !/*fi         15*/
      return                                                                    !/*fi         16*/
      end                                                                       !/*fi         17*/
