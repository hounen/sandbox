      function energy (a,z)                                                     !/*en          2*/
#include <lcs/double.h>                                                         /*!en          3*/
#ifdef OLDM                                                                     /*!en          4*/
#include <lcs/lptS.h>                                                           /*!en          5*/
#include <lcs/ercom.h>                                                          /*!en          6*/
      dimension jprime(250)                                                     !/*en          7*/
      data jprime /19*0,10*1,8*2,7*3,7*4,6*5,5*6,6*7,5*8,5*9,5*10,5*11,4        !/*en          8*/
     & *12,5*13,4*14,4*15,4*16,4*17,4*18,4*19,4*20,4*21,4*22,3*23,4*24,4        !/*en          9*/
     & *25,3*26,4*27,3*28,4*29,3*30,3*31,4*32,3*33,3*34,4*35,3*36,3*37,3        !/*en         10*/
     & *38,3*39,3*40,3*41,3*42,3*43,3*44,3*45,3*46,3*47,3*48,3*49,3*50,3        !/*en         11*/
     & *51,3*52,3*53,3*54,55,55,3*56,3*57,3*58,2*59,2*60/                       !/*en         12*/
      cam(a,z,b)=8.36755d0*a-0.78244d0*z-17.0354d0*a*(dp1-1.84619d0*(a          !/*en         13*/
     & -dp2*z)**2/a**2)+25.8357d0*b**2*(dp1-1.71219d0*(a-dp2*z)**2/a**2)        !/*en         14*/
     & *(dp1-0.62025d0/b**2)**2+0.779d0*z*(z-dp1)*(dp1-1.5849d0/b**2+1.2        !/*en         15*/
     & 273d0/a+1.5772d0/(a*b))/b-0.4323d0*exp(1.3333333333d0*log(z))*           !/*en         16*/
     & (dp1-0.57811d0/b-0.14518d0/b**2+0.49597d0/a)/b                           !/*en         17*/
!......................................................................         !/*en         18*/
!      deltas (a,b)=(a-1.0)/(1.0+(124.0/b**2))                                  !/*en         19*/
!      i=a                                                                      !/*en         20*/
!      a3=exp(log(a)/dp3)                                                       !/*en         21*/
!      jprime(i)=deltas(a,a3)                                                   !/*en         22*/
!......................................................................         !/*en         23*/
      i=a                                                                       !/*en         24*/
      kz=z                                                                      !/*en         25*/
      j=i-2*kz-jprime(i)+10                                                     !/*en         26*/
      if (j.gt.0.and.j.le.20.and.i.le.250) then                                 !/*en         27*/
        energy=waps(i,j)                                                        !/*en         28*/
        if (energy.ne.dp0) return                                               !/*en         29*/
      endif                                                                     !/*en         30*/
      n=a-z                                                                     !/*en         31*/
      a3=exp(0.3333333333d0*log(a))                                             !/*en         32*/
      energy=cam(a,z,a3)+cam2(kz)+cam3(n)                                       !/*en         33*/
#else                                                                           /*!en         34*/
      character*1 c                                                             !/*en         35*/
      energy=xm_atm (a,z,c)                                                     !/*en         36*/
#endif                                                                          /*!en         37*/
      return                                                                    !/*en         38*/
      end                                                                       !/*en         39*/
