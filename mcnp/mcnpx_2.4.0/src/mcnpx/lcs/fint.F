      function fint (xl,xh)                                                     !/*fi          2*/
#include <lcs/double.h>                                                         /*!fi          3*/
!     performs integral of exp(x)/x**2 from xl to xh                            !/*fi          4*/
!     timimg: from 12.8 to 23.4 microseconds on cdc7600                         !/*fi          5*/
!     and from 7.0 to 12.3 microseconds on cray                                 !/*fi          6*/
!     accuracy: better than .05 percent                                         !/*fi          7*/
      dimension tab1(66), tab2(80)                                              !/*fi          8*/
      data tab1 /.50000,.50847,.51724,.52631,.53570,.54542,.55549,.56593        !/*fi          9*/
     & ,.57675,.58797,.59962,.61171,.62427,.63732,.65088,.66499,.67966,.        !/*fi         10*/
     & 69493,.71084,.72740,.74467,.76268,.78146,.80106,.82153,.84290,.86        !/*fi         11*/
     & 525,.88861,.91304,.93861,.96539,.99343,1.02282,1.05363,1.08595,1.        !/*fi         12*/
     & 11987,1.15547,1.19287,1.23218,1.27350,1.31696,1.36269,1.41083,1.4        !/*fi         13*/
     & 6154,1.51497,1.57129,1.63069,1.69337,1.75953,1.82939,1.90320,1.98        !/*fi         14*/
     & 121,2.06370,2.15096,2.24331,2.34108,2.44463,2.55436,2.67068,2.794        !/*fi         15*/
     & 03,2.92489,3.06377,3.21123,3.36785,3.53427,3.71116/                      !/*fi         16*/
      data tab2 /.04135,.22059,.50078,.80624,1.08109,1.29772,1.44991,1.5        !/*fi         17*/
     & 4374,1.59063,1.60296,1.59178,1.56602,1.53227,1.49518,1.45778,1.42        !/*fi         18*/
     & 190,1.38856,1.35821,1.33093,1.30662,1.28505,1.26593,1.24899,1.233        !/*fi         19*/
     & 94,1.22054,1.20857,1.19782,1.18813,1.17936,1.17139,1.16412,1.1574        !/*fi         20*/
     & 5,1.15132,1.14566,1.14043,1.13556,1.13103,1.12679,1.12283,1.11912        !/*fi         21*/
     & ,1.11562,1.11233,1.10922,1.10629,1.10350,1.10087,1.09836,1.09598,        !/*fi         22*/
     & 1.09371,1.09155,1.08948,1.08751,1.08563,1.08382,1.08209,1.08043,1        !/*fi         23*/
     & .07883,1.07730,1.07583,1.07441,1.07304,1.07173,1.07046,1.06923,1.        !/*fi         24*/
     & 06805,1.06691,1.06580,1.06473,1.06370,1.06270,1.06173,1.06079,1.0        !/*fi         25*/
     & 5987,1.05899,1.05813,1.05729,1.05648,1.05569,1.05493,1.05418/            !/*fi         26*/
      x=xl                                                                      !/*fi         27*/
      if (x.lt.6.5) then                                                        !/*fi         28*/
        i=10.0*x                                                                !/*fi         29*/
        temp=tab1(i+1)+(tab1(i+2)-tab1(i+1))*(10.0*x-real(i))                   !/*fi         30*/
        func1=x*temp                                                            !/*fi         31*/
      else                                                                      !/*fi         32*/
        if (x.lt.40.0) then                                                     !/*fi         33*/
          i=dp2*x                                                               !/*fi         34*/
          temp=tab2(i)+(tab2(i+1)-tab2(i))*(dp2*x-real(i))                      !/*fi         35*/
        else                                                                    !/*fi         36*/
          temp=dp1+(dp2+6.7/x)/x                                                !/*fi         37*/
        endif                                                                   !/*fi         38*/
        temp=temp*exp(x)/x**2                                                   !/*fi         39*/
        func1=temp                                                              !/*fi         40*/
      endif                                                                     !/*fi         41*/
      x=xh                                                                      !/*fi         42*/
      if (x.lt.6.5) then                                                        !/*fi         43*/
        i=10.0*x                                                                !/*fi         44*/
        temp=tab1(i+1)+(tab1(i+2)-tab1(i+1))*(10.0*x-real(i))                   !/*fi         45*/
        func2=x*temp                                                            !/*fi         46*/
      else                                                                      !/*fi         47*/
        if (x.lt.40.0) then                                                     !/*fi         48*/
          i=dp2*x                                                               !/*fi         49*/
          temp=tab2(i)+(tab2(i+1)-tab2(i))*(dp2*x-real(i))                      !/*fi         50*/
        else                                                                    !/*fi         51*/
          temp=dp1+(dp2+6.7/x)/x                                                !/*fi         52*/
        endif                                                                   !/*fi         53*/
        temp=temp*exp(x)/x**2                                                   !/*fi         54*/
        func2=temp                                                              !/*fi         55*/
      endif                                                                     !/*fi         56*/
      fint=func2-func1-dp1/xh+dp1/xl+log(xh/xl)                                 !/*fi         57*/
      return                                                                    !/*fi         58*/
      end                                                                       !/*fi         59*/
